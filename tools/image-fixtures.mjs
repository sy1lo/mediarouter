/**
 * **尾行验证专用**：5 张，刻意让末行只剩 1 张。
 *
 * 这是用户反馈的现场：末行不满时，最后一格曾被取整误差修正**横向撑大**
 * 到整行宽度（实测 188px → 818px，4.3 倍），盒子比例与图片比例脱节，
 * `object-fit` 就把画面裁掉一大块 —— 表现就是"右下角那张只显示了一部分"。
 *
 * 数量选 5 是因为在常见容器宽度下它会排成「4 + 1」：
 * 前 4 张的宽高比之和已经够宽、收行，剩下 1 张单独成行且**远远不满**。
 * 最后一张用 1:1（方图）：一旦被撑宽，比例偏差会大到一眼可见。
 */
const TAIL = [
  ['晨光', 4000, 2250],
  ['背影', 3000, 4000],
  ['天台', 4500, 3000],
  ['黄昏', 5000, 2000],
  ['方寸', 2400, 2400], // 1:1，末行唯一一张
]

function build(prefix, list) {
  return list.map(([name, w, h], i) => ({ id: `${prefix}${i + 1}`, name, w, h }))
}

export const COLLECTIONS = [
  { id: 'main', name: '2026 春季旅行', files: build('m', MAIN) },
  { id: 'sub', name: '竖构图练习', files: build('s', SUB) },
  // 名字要像真的相册（截图会被用在 README 里），但它的用途是验尾行：
  // `?case=image&col=街拍速写` 直接打开它
  { id: 'tail', name: '街拍速写', files: build('t', TAIL) },
]

