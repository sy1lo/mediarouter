/**
 * 图片分类的验证素材（仅用于 Edge 无头验证，不参与 vite 构建）。
 *
 * 为什么要有这个文件：
 *   平铺填满的布局最容易在**极端宽高比**上翻车 —— 竖图会把整行撑高、
 *   全景图会把整行压扁、方图会让相邻两行的节奏对不上。
 *   所以这里刻意混入 16:9 / 3:2 / 4:3 / 1:1 / 2:3 / 3:1 / 2.5:1 各类比例。
 *
 * 消费方是 `inject-mock.mjs`：它把这份清单注入成 `window.__MOCK_IMAGES`，
 * `mock-bridge.js` 再据此建出带 `width`/`height` 的媒体库
 * （模拟后端 `imagedims` 的输出），并按同一份宽高比生成缩略图。
 *
 * 单一数据源：下发的宽高与缩略图的形状都从这里取 —— 对不上的话
 * 布局算出来和实际渲染的图不一致，验证结论就废了。
 */

